# gen-config-xml.ps1 -- render res/values/config.xml from a JSON spec.
# ASCII only by design.
#
# Why: /sdcard/Android/data/<pkg>/ is not writable by adbd (EACCES even after the app creates it),
# so runtime config.json cannot be pushed. Compile the defaults into resources instead.
#
# Usage:
#   powershell -ExecutionPolicy Bypass -File .\gen-config-xml.ps1 -Json .\assets\config.sample.json
#   powershell -ExecutionPolicy Bypass -File .\gen-config-xml.ps1 -Json .\cfg.json -OutFile .\app\src\main\res\values\config.xml

param(
    [Parameter(Mandatory=$true)][string]$Json,
    [string]$OutFile,
    [string]$Header = 'Generated by gen-config-xml.ps1 - edit the JSON, not this file.'
)

$ErrorActionPreference = 'Stop'
if (-not (Test-Path $Json)) { throw "JSON not found: $Json" }

$raw = [System.IO.File]::ReadAllText((Resolve-Path $Json).Path, [System.Text.Encoding]::UTF8)
$cfg = $raw | ConvertFrom-Json

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$sb.AppendLine("<!-- $Header -->")
[void]$sb.AppendLine('<resources>')

function Esc([string]$s) {
    $s = $s.Replace('&','&amp;').Replace('<','&lt;').Replace('>','&gt;')
    return $s.Replace('"','\"').Replace("'","\'")
}

if ($cfg.bools) {
    foreach ($p in $cfg.bools.PSObject.Properties) {
        $v = if ($p.Value) { 'true' } else { 'false' }
        [void]$sb.AppendLine("    <bool name=`"$($p.Name)`">$v</bool>")
    }
}

if ($cfg.integers) {
    foreach ($p in $cfg.integers.PSObject.Properties) {
        [void]$sb.AppendLine("    <integer name=`"$($p.Name)`">$($p.Value)</integer>")
    }
}

if ($cfg.strings) {
    foreach ($p in $cfg.strings.PSObject.Properties) {
        $v = Esc ([string]$p.Value)
        [void]$sb.AppendLine("    <string name=`"$($p.Name)`">$v</string>")
    }
}

if ($cfg.arrays) {
    foreach ($p in $cfg.arrays.PSObject.Properties) {
        $name = $p.Name
        [void]$sb.AppendLine("    <string-array name=`"$name`">")
        foreach ($item in $p.Value) {
            [void]$sb.AppendLine("        <item>$(Esc ([string]$item))</item>")
        }
        [void]$sb.AppendLine("    </string-array>")
    }
}

[void]$sb.AppendLine('</resources>')

$text = $sb.ToString()
if ($OutFile) {
    $dir = Split-Path -Parent $OutFile
    if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Path $dir -Force | Out-Null }
    [System.IO.File]::WriteAllText($OutFile, $text, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "wrote $OutFile"
} else {
    Write-Output $text
}
